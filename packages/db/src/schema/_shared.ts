/**
 * PORTABLE COLUMN HELPERS
 * -----------------------
 * All schema files use only the subset of column types that have a 1:1 mapping
 * between `drizzle-orm/sqlite-core` and `drizzle-orm/pg-core`. There are no
 * SQLite-only DDL features (no STRICT tables, no WITHOUT ROWID, no generated
 * columns, no CHECK constraints beyond enums modelled as text unions).
 *
 * Migration path to PostgreSQL later:
 *   1. Swap the `drizzle-orm/sqlite-core` import for `drizzle-orm/pg-core`
 *      in the schema files.
 *   2. Map `text id` -> `uuid`, `integer(..., {mode:'boolean'})` -> `boolean`,
 *      `integer` money -> `numeric(12,2)` or keep bigint minor units.
 *   3. Re-run `drizzle-kit generate` against a PG connection; data migrates
 *      through a one-off ETL because ISO timestamps and UUIDs are preserved.
 *
 * Why client-generated UUID ids? Offline kiosks create rows before the server
 * ever sees them. Autoincrement integers would collide on merge. UUIDv7 gives
 * globally unique ids AND time-ordering for index locality.
 */
import { integer, text } from 'drizzle-orm/sqlite-core';
import { uuidv7 } from '../ids';

/**
 * Primary key. `$defaultFn` (not a DB default) so the value is generated by the
 * client that creates the row — the kiosk keeps its own id even if the server
 * assigns one later, and inserts may still pass an explicit id when the caller
 * already minted one.
 */
export const id = () => text('id').primaryKey().$defaultFn(() => uuidv7());

export const createdAt = () =>
  text('created_at')
    .notNull()
    .$defaultFn(() => new Date().toISOString());

export const updatedAt = () =>
  text('updated_at')
    .notNull()
    .$defaultFn(() => new Date().toISOString())
    .$onUpdateFn(() => new Date().toISOString());

export const deletedAt = () => text('deleted_at');

/** Boolean stored as 0/1 — maps to PG boolean. */
export const flag = (name: string, defaultValue = false) =>
  integer(name, { mode: 'boolean' }).notNull().default(defaultValue);

/** Money in minor units (cents/sen) — never floats. Maps to PG integer/bigint. */
export const cents = (name: string) => integer(name).notNull();

/** ISO-8601 timestamp stored as text — maps to PG timestamptz. */
export const iso = (name: string) => text(name).notNull();

export const nullableIso = (name: string) => text(name);

/** JSON stored as text — maps to PG jsonb. */
export const json = <T>(name: string) => text(name, { mode: 'json' }).$type<T>();

/** Non-null integer with a default — counters, stripe indices, versions. */
export const counter = (name: string, defaultValue = 0) =>
  integer(name).notNull().default(defaultValue);
